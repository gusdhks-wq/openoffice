export function approvalLanguage(header = '') {
  for (const entry of String(header).toLowerCase().split(',')) {
    const full = entry.split(';')[0].trim(),
      base = full.split('-')[0]
    if (Object.hasOwn(approvalMessages, full)) return full
    if (Object.hasOwn(approvalMessages, base)) return base
  }
  return 'en'
}
